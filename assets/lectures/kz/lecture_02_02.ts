const content = `
# Жолдар және мәтін: \`String\` типі, жолдармен жұмыс

## 1. \`String\` деген не

\`String\` — бұл **мәтінді сақтауға арналған деректер типі**.  
Жолдар — **қос тырнақшаға** \`" "\` алынған таңбалар тізбегі.

Мысалдар:

\`\`\`
String name = "Вася";
String greeting = "Привет, мир!";
String empty = ""; // бос жол
\`\`\`

> ⚠️ Бір тырнақша ' ' тек бір таңба (\`char\`) үшін қолданылады, мәтін үшін емес.

## 2. Жолдарды жариялау және мән беру

Алдымен айнымалыны жариялауға болады:

\`\`\`
String text;
\`\`\`

Содан кейін оған мән беруге болады:

\`\`\`
text = "Java";
\`\`\`

Немесе жариялау кезінде бірден:

\`\`\`
String message = "Қош келдіңіз!";
\`\`\`

## 3. Конкатенация (жолдарды біріктіру)

Java тілінде жолдарды \`+\` операторы арқылы біріктіруге болады:

\`\`\`
String firstName = "Вася";
String lastName = "Петров";
String fullName = firstName + " " + lastName;
System.out.println(fullName); // Вася Петров
\`\`\`

**Жолдарды** және **сандарды** да біріктіруге болады:

\`\`\`
int age = 18;
String text = "Жасы: " + age;
System.out.println(text); // Жасы: 18
\`\`\`

## 4. Жолдың ұзындығы

Жолда қанша таңба бар екенін білу үшін \`.length()\` әдісін қолданамыз:

\`\`\`
String s = "Hello";
System.out.println(s.length()); // 5
\`\`\`

## 5. Бірнеше жолды біріктіру

\`\`\`
String s1 = "Сәлем";
String s2 = "әлем";
String s3 = s1 + ", " + s2 + "!";
System.out.println(s3); // Сәлем, әлем!
\`\`\`

## 6. Таңбаларды экранирлеу

Кейбір таңбалар **арнайы белгілеуді** қажет етеді:

| Таңба | Қолданылуы |
| ------ | ---------- |
| \`\\"\`   | қос тырнақша |
| \`\\\\\`   | кері қиғаш сызық |
| \`\\n\`   | жаңа жолға көшу |
| \`\\t\`   | табуляция |

Мысал:

\`\`\`
System.out.println("Ол айтты: \\"Сәлем!\\"\\nЖаңа жол.");
\`\`\`

Шығару:

\`\`\`
Ол айтты: "Сәлем!"
Жаңа жол.
\`\`\`

## 7. Жолдық әдістер (негізгілері)

\`\`\`
String text = "JavaRush";

// Ұзындығын тексеру
int len = text.length(); // 8

// Жоғарғы/төменгі регистрге түрлендіру
String upper = text.toUpperCase(); // JAVARUSH
String lower = text.toLowerCase(); // javarush

// Индекс бойынша таңба алу
char c = text.charAt(0); // 'J'

// Жолдарды салыстыру
boolean equals = text.equals("JavaRush"); // true
boolean equalsIgnoreCase = text.equalsIgnoreCase("javarush"); // true

// Жолдың басын/соңын тексеру
boolean starts = text.startsWith("Java"); // true
boolean ends = text.endsWith("Rush"); // true
\`\`\`

> Жолдағы индекстер 0-ден басталады.

## 8. Жолдармен жұмыс істейтін бағдарлама мысалы

\`\`\`
String firstName = "Иван";
String lastName = "Иванов";
int age = 20;

String info = "Аты: " + firstName + ", Тегі: " + lastName + ", жасы: " + age;
System.out.println(info);
\`\`\`

Шығару:

\`\`\`
Аты: Иван, Тегі: Иванов, жасы: 20
\`\`\`

## Қорытынды

- \`String\` мәтіндік деректерді сақтайды.
- Жолдарды біріктіру үшін \`+\` қолданылады.
- Негізгі әдістер: \`.length()\`, \`.toUpperCase()\`, \`.toLowerCase()\`, \`.charAt()\`, \`.equals()\`.
- Ыңғайлы шығару үшін жолдарды сандармен біріктіруге болады.
- Арнайы таңбалар үшін экранирлеу тізбектері қолданылады (\`\\"\`, \`\\\\\`, \`\\n\`, \`\\t\`).
`;

