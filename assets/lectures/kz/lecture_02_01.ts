const content = `
# Бүтін сандар: \`int\` типі, \`int\` типімен операциялар

## 1. \`int\` типі

\`int\` — бұл **примитивті деректер типі**, ол бүтін сандарды (бөлшек бөлігі жоқ) сақтайды.  
Мәндер диапазоны: \`-2_147_483_648\`-ден \`2_147_483_647\`-ге дейін.

Мысалдар:

\`\`\`
int a = 10;
int b = -5;
int c = 0;
\`\`\`

- \`a\` оң санды сақтайды
- \`b\` — теріс санды
- \`c\` — нөлді

## 2. \`int\` типті айнымалыны жариялау

\`int\` типті айнымалы жасау үшін:

\`\`\`
int number;
\`\`\`

Мұнда **number** айнымалысы жарияланған, бірақ әлі мәні жоқ.

Мәнді бірден беруге болады:

\`\`\`
int number = 15;
\`\`\`

## 3. \`int\` типімен арифметикалық операциялар

Java бүтін сандар үшін стандартты операцияларды қолдайды:

| Оператор | Әрекет              | Мысал          |
| -------- | ------------------- | -------------- |
| \`+\`      | қосу                | \`5 + 3 = 8\`   |
| \`-\`      | азайту              | \`5 - 3 = 2\`   |
| \`*\`      | көбейту             | \`5 * 3 = 15\`  |
| \`/\`      | бөлу (бүтін бөлу)   | \`5 / 2 = 2\`   |
| \`%\`      | бөлуден қалған қалдық | \`5 % 2 = 1\` |

Кодтағы мысал:

\`\`\`
int a = 10;
int b = 3;

System.out.println(a + b); // 13
System.out.println(a - b); // 7
System.out.println(a * b); // 30
System.out.println(a / b); // 3
System.out.println(a % b); // 1
\`\`\`

> ⚠️ \`int / int\` бөлу кезінде бөлшек бөлік алынып тасталады. Бөлшек нәтиже алу үшін операндтардың кем дегенде біреуі \`double\` болуы керек.

## 4. Операциялар басымдығы

Өрнектерді орындау реті:

1. \`*\`, \`/\`, \`%\`
2. \`+\`, \`-\`

Мысал:

\`\`\`
int x = 2 + 3 * 4; // 14, алдымен 3*4, содан кейін +2
\`\`\`

Жақшалар ретті өзгертеді:

\`\`\`
int y = (2 + 3) * 4; // 20
\`\`\`

## 5. Айнымалы мәнін өзгерту

\`\`\`
int count = 5;
count = count + 3; // 8
\`\`\`

Қысқартылған нұсқасы:

\`\`\`
count += 3; // дәл сол әрекет
count -= 2; // 2-ге азайту
count *= 2; // 2-ге көбейту
count /= 4; // 4-ке бөлу
count %= 3; // 3-ке бөлгендегі қалдық
\`\`\`

## 6. Инкремент және декремент

\`\`\`
int x = 5;
x++; // x = 6
x--; // x = 5
\`\`\`

Оларды **айнымалының алдында** немесе **соңында** қолдануға болады. Күрделі өрнектерде есептеу тәртібіне әсер етеді.

## 7. Есептер мысалдары

\`\`\`
int a = 7;
int b = 2;

System.out.println(a + b); // 9
System.out.println(a / b); // 3
System.out.println(a % b); // 1
\`\`\`

\`\`\`
int x = 10;
x += 5;   // x = 15
x--;      // x = 14
\`\`\`

## Қорытынды

- \`int\` — бүтін сандарға арналған тип.
- Операциялар: \`+\`, \`-\`, \`*\`, \`/\`, \`%\`.
- \`int / int\` бөлуі бөлшек бөлікті алып тастайды.
- Айнымалыларды \`=\`, \`+=\`, \`-=\`, \`*=\`, \`/=\`, \`%=\` арқылы өзгертуге болады.
- \`++\` инкременті және \`--\` декременті — мәнді 1-ге тез арттыру немесе азайту тәсілі.
`;

